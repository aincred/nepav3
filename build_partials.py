"""Rebuilds js/partials-bundle.js from partials/header.html and partials/footer.html.
Run this after editing a partial if you open index.html by double-clicking (file://):
    python build_partials.py
(Not needed when the site is served from a web server - the HTML files are loaded directly.)"""
import json, pathlib
root = pathlib.Path(__file__).parent
files = ["partials/header.html", "partials/footer.html"]
data = {f: (root / f).read_text(encoding="utf-8") for f in files}
out = "/* AUTO-GENERATED by build_partials.py - do not edit. Edit the files in partials/ instead. */\n"
out += "window.NEPA_PARTIALS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
(root / "js" / "partials-bundle.js").write_text(out, encoding="utf-8")
print("Wrote js/partials-bundle.js")
